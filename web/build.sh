#!/usr/bin/env bash
# Builds the web playground: compiles the kc compiler to WebAssembly with
# Emscripten, and bundles the example programs. Run inside WSL.
# Output: web/kc.js (compiler, with the .wasm embedded) and web/examples.js.
# Then open web/index.html in a browser (double-click works, no server needed).
set -euo pipefail

WEB="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC="$WEB/../src"
source "$HOME/emsdk/emsdk_env.sh" > /dev/null 2>&1

# The same compiler sources as the native build, minus main.cpp (the CLI).
SOURCES=()
for f in "$SRC"/*.cpp "$SRC"/opt/*.cpp; do
  [[ "$f" == */main.cpp ]] || SOURCES+=("$f")
done

em++ -std=c++17 -O2 -fexceptions -I "$SRC" "${SOURCES[@]}" "$WEB"/kc_web.cpp \
  -sEXPORTED_FUNCTIONS=_kc_explore -sEXPORTED_RUNTIME_METHODS=ccall \
  -sMODULARIZE=1 -sEXPORT_NAME=createKc -sENVIRONMENT=web \
  -sSINGLE_FILE=1 -sALLOW_MEMORY_GROWTH=1 \
  -o "$WEB/kc.js"

# examples.js: every examples/*.kc file as a JavaScript object {name: source}.
python3 - "$WEB/../examples" "$WEB/examples.js" <<'PY'
import json, sys
from pathlib import Path
examples = {p.stem: p.read_text() for p in sorted(Path(sys.argv[1]).glob("*.kc"))}
Path(sys.argv[2]).write_text("// Generated by web/build.sh from examples/*.kc\nconst KC_EXAMPLES = "
                             + json.dumps(examples, indent=1) + ";\n")
PY

echo "built $WEB/kc.js ($(du -h "$WEB/kc.js" | cut -f1)) and $WEB/examples.js"
